#!/usr/bin/env node
// Scans the gateway skill tool specs (lambda/skills/<skill>/tool_spec.json) and
// emits src/generated/gatewayTools.ts — the authoritative name+description list
// for a TOOL_DESCRIPTION_RECOMMENDATION input. The AgentCore optimizer requires
// >=1 tool; the SPA has no live gateway access (the gateway is CUSTOM_JWT / M2M,
// not reachable from the browser), so the descriptions are baked in at build
// time from the same specs the gateway targets are configured with.
//
// Tool names MUST match what the agent's traces record: the gateway exposes each
// operation as `<target-name>___<operation>` (see agent/main.py ALLOWED_TOOLS =
// "mcp__mlops-gateway__*", and the skill docs, e.g. `git-skill___commit_experiment`).
// The target names are NOT a pure transform of the spec directory (web_search ->
// web-search-skill), so the mapping is encoded explicitly below to mirror
// gateway-stack.ts targetDefs.
import { readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(__dirname, "..");
const repoRoot = resolve(frontendRoot, "..");

// schema-dir (lambda/skills/<dir>) -> gateway target name. Must match the
// targetDefs table in cdk/lib/stacks/backend/gateway-stack.ts exactly.
const TARGETS = [
  { dir: "sagemaker", target: "sagemaker-skill" },
  { dir: "huggingface", target: "huggingface-skill" },
  { dir: "git", target: "git-skill" },
  { dir: "mlflow", target: "mlflow-skill" },
  { dir: "slurm", target: "slurm-skill" },
  { dir: "web_search", target: "web-search-skill" },
  { dir: "hyperpod", target: "hyperpod-skill" },
];

// Prefer the staged copy (frontend/.agent-skills/tool-specs) so CodeBuild — which
// only sees the zipped frontend/ tree — can read the specs. Fall back to the repo
// layout for local dev before staging has run.
const stagedSpecs = join(frontendRoot, ".agent-skills", "tool-specs");
const repoSpecs = join(repoRoot, "lambda", "skills");
const specsRoot = statSync(stagedSpecs, {
  throwIfNoEntry: false,
})?.isDirectory()
  ? stagedSpecs
  : repoSpecs;

const outTs = join(frontendRoot, "src", "generated", "gatewayTools.ts");

function fail(msg) {
  console.error(`[build-tools-manifest] ${msg}`);
  process.exit(1);
}

const tools = [];
for (const { dir, target } of TARGETS) {
  const p = join(specsRoot, dir, "tool_spec.json");
  if (!statSync(p, { throwIfNoEntry: false })?.isFile())
    fail(`Missing tool spec: ${p}`);
  const spec = JSON.parse(readFileSync(p, "utf8"));
  if (!Array.isArray(spec) || spec.length === 0)
    fail(`Tool spec ${p} is not a non-empty array`);
  for (const t of spec) {
    if (typeof t.name !== "string" || !t.name)
      fail(`Tool in ${p} has no name`);
    tools.push({
      toolName: `${target}___${t.name}`,
      description: typeof t.description === "string" ? t.description : "",
    });
  }
}

if (tools.length === 0) fail("No tools discovered across specs");

mkdirSync(dirname(outTs), { recursive: true });
const header =
  "// AUTO-GENERATED by scripts/build-tools-manifest.mjs. Do not edit.\n";
const type =
  "export type GatewayTool = { toolName: string; description: string };\n";
writeFileSync(
  outTs,
  header +
    type +
    `export const gatewayTools: GatewayTool[] = ${JSON.stringify(tools, null, 2)};\n`,
);
console.log(`[build-tools-manifest] wrote ${tools.length} gateway tools`);
