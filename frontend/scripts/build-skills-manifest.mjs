#!/usr/bin/env node
// Scans agent/.claude/skills/*/SKILL.md, emits src/generated/skills.ts,
// and copies assets/images/architecture/architecture.png -> public/.
import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  readdirSync,
  statSync,
  copyFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const __dirname = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(__dirname, "..");
const repoRoot = resolve(frontendRoot, "..");
// Prefer staged copy (.agent-skills/) so CodeBuild — which only sees the
// zipped frontend/ directory — can read skills without reaching outside it.
// Fall back to the repo layout for local dev before staging has run.
const stagedSkills = join(frontendRoot, ".agent-skills", "skills");
const stagedArch = join(frontendRoot, ".agent-skills", "architecture.png");
const repoSkills = join(repoRoot, "agent", ".claude", "skills");
const repoArch = join(
  repoRoot,
  "assets",
  "images",
  "architecture",
  "architecture.png",
);
const skillsDir = statSync(stagedSkills, {
  throwIfNoEntry: false,
})?.isDirectory()
  ? stagedSkills
  : repoSkills;
const archSrc = statSync(stagedArch, { throwIfNoEntry: false })?.isFile()
  ? stagedArch
  : repoArch;
const outTs = join(frontendRoot, "src", "generated", "skills.ts");
const publicDir = join(frontendRoot, "public");

function fail(msg) {
  console.error(`[build-skills-manifest] ${msg}`);
  process.exit(1);
}

if (!statSync(skillsDir, { throwIfNoEntry: false })?.isDirectory())
  fail(`Missing ${skillsDir}`);
if (!statSync(archSrc, { throwIfNoEntry: false })?.isFile())
  fail(`Missing ${archSrc}`);

const skills = readdirSync(skillsDir)
  .filter((n) => statSync(join(skillsDir, n)).isDirectory())
  .map((id) => {
    const p = join(skillsDir, id, "SKILL.md");
    if (!statSync(p, { throwIfNoEntry: false })?.isFile()) fail(`Missing ${p}`);
    const { data, content } = matter(readFileSync(p, "utf8"));
    return {
      id,
      name: data.name ?? id,
      description: data.description ?? "",
      body: content,
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

mkdirSync(dirname(outTs), { recursive: true });
const header =
  "// AUTO-GENERATED by scripts/build-skills-manifest.mjs. Do not edit.\n";
const type =
  "export type Skill = { id: string; name: string; description: string; body: string };\n";
writeFileSync(
  outTs,
  header +
    type +
    `export const skills: Skill[] = ${JSON.stringify(skills, null, 2)};\n`,
);

mkdirSync(publicDir, { recursive: true });
copyFileSync(archSrc, join(publicDir, "architecture.png"));
console.log(
  `[build-skills-manifest] wrote ${skills.length} skills, copied architecture.png`,
);
